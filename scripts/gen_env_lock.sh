#!/usr/bin/env bash
set -euo pipefail

# Snapshots the pip layer of the slamlab conda env into scripts/locks/slamlab.lock.
#
# The lock freezes the whole resolved pip tree, so setup_slamlab.sh replays a known-good
# set instead of resolving whatever is newest. Excluded: the editable installs (slamlab,
# slamlab_rs) and the conda layer (Python, cmake, compilers, Rust), which pip cannot see.
# Linux x86_64 and Python-version specific. Regenerate after a deliberate upgrade:
#   scripts/gen_env_lock.sh [--env NAME]

ENV_NAME="slamlab"
[[ "${1:-}" == "--env" ]] && ENV_NAME="$2"

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK_FILE="${ROOT_DIR}/scripts/locks/slamlab.lock"
CONDA_BIN="${CONDA_EXE:-$(command -v conda || echo "${HOME}/miniconda3/condabin/conda")}"

mkdir -p "$(dirname "${LOCK_FILE}")"
py_version="$("${CONDA_BIN}" run -n "${ENV_NAME}" python -c 'import platform; print(platform.python_version())')"
{
  echo "# pip layer of the '${ENV_NAME}' conda env -- generated by scripts/gen_env_lock.sh"
  echo "# python ${py_version}, linux x86_64"
  "${CONDA_BIN}" run -n "${ENV_NAME}" python -m pip list --format=freeze --exclude-editable \
    | grep -v -E '^(slamlab|slamlab[-_]rs)( @|==)'
} > "${LOCK_FILE}"
echo "wrote ${LOCK_FILE}"
