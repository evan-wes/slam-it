#!/usr/bin/env bash
set -euo pipefail

# Snapshots the pip layer of the slam-it conda env into scripts/locks/slam-it.lock.
#
# The lock freezes the whole resolved pip tree, so setup_slam_it.sh replays a known-good
# set instead of resolving whatever is newest. Excluded: the editable installs (slam-it,
# slam-it-rs), the conda layer (Python, cmake, compilers, Rust), which pip cannot see, and
# GTSAM's Python wrapper, which setup_slam_it.sh builds from source rather than from an index.
# Linux x86_64 and Python-version specific. Regenerate after a deliberate upgrade:
#   scripts/gen_env_lock.sh [--env NAME]

ENV_NAME="slam-it"
[[ "${1:-}" == "--env" ]] && ENV_NAME="$2"

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK_FILE="${ROOT_DIR}/scripts/locks/slam-it.lock"
CONDA_BIN="${CONDA_EXE:-$(command -v conda || echo "${HOME}/miniconda3/condabin/conda")}"

mkdir -p "$(dirname "${LOCK_FILE}")"
py_version="$("${CONDA_BIN}" run -n "${ENV_NAME}" python -c 'import platform; print(platform.python_version())')"
{
  echo "# pip layer of the '${ENV_NAME}' conda env -- generated by scripts/gen_env_lock.sh"
  echo "# python ${py_version}, linux x86_64"
  "${CONDA_BIN}" run -n "${ENV_NAME}" python -m pip list --format=freeze --exclude-editable \
    | grep -v -E '^(slam[-_]it[-_]all|slam[-_]it[-_]all[-_]rs|gtsam)( @|==)'
} > "${LOCK_FILE}"
echo "wrote ${LOCK_FILE}"
